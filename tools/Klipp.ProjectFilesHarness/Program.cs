if (args.Contains("--ripple-sync-only"))
{
    RippleSyncChecks.Run();
    return;
}

var root = Path.Combine(Path.GetTempPath(), "Klipp-ProjectFiles-" + Guid.NewGuid().ToString("N"));
Directory.CreateDirectory(root);
var checks = 0;
void Check(bool condition, string message)
{
    if (!condition) throw new InvalidOperationException(message);
    checks++;
}
async Task<string> Asset(string folder, string name, string contents)
{
    var directory = Path.Combine(root, folder);
    Directory.CreateDirectory(directory);
    var path = Path.Combine(directory, name);
    await File.WriteAllTextAsync(path, contents);
    return path;
}

var video = await Asset("originals/a", "same.mp4", "first-video-payload");
var otherVideo = await Asset("originals/b", "same.mp4", "second-video-payload");
var audio = await Asset("originals/audio", "music.wav", "music-payload");
var image = await Asset("originals/images", "logo.png", "image-payload");
var font = await Asset("originals/fonts", "custom.ttf", "font-payload");
var lut = await Asset("originals/luts", "grade.cube", "TITLE sample\nLUT_3D_SIZE 2");
var processingOriginal = await Asset("originals/processing", "original.mp4", "unprocessed-video-payload");
var previousBake = await Asset("originals/processing", "previous-bake.mp4", "previous-bake-payload");
var project = new EditorProject
{
    Name = "Portable test",
    Clips = [new() { SourcePath = video, SourceDurationSeconds = 10, TrimEndSeconds = 10, LutPath = lut },
        new() { SourcePath = otherVideo, SourceDurationSeconds = 5, TrimEndSeconds = 5,
            Track = EditorClipTrack.Overlay, TimelineStartSeconds = 2 }],
    AudioTracks = [new() { SourcePath = video, SourceDurationSeconds = 10, TrimEndSeconds = 10 },
        new() { SourcePath = audio, SourceDurationSeconds = 10, TrimEndSeconds = 10 }],
    GraphicLayers = [new() { SourcePath = image, StartSeconds = 0, EndSeconds = 3 }],
    ExtraTextLayers = [new() { Text = "Title", FontFilePath = font, StartSeconds = 0, EndSeconds = 3 }],
    SubtitleLayers = [new() { Text = "Caption", FontFilePath = font, StartSeconds = 0, EndSeconds = 3 }],
    Settings = new() { TextFontFilePath = font, SubtitleFontFilePath = font }
};
project.Normalize();
project.Clips[0].VideoProcessing = new EditorProjectVideoProcessingState
{
    OriginalSourcePath = processingOriginal, BakedSourcePath = previousBake,
    OriginalSourceDurationSeconds = 10, OriginalTrimEndSeconds = 10, IsApplied = false
};
var projectDirectory = Path.Combine(root, "Projects");
var service = new EditorProjectService(projectDirectory);
await service.SaveVersionAsync(project);
var versions = await service.ListBackupsAsync(project.Id);
Check(versions.Count == 1, "Manual version was not saved.");
Check((await service.TryLoadAsync(versions[0].ProjectPath))?.Clips[0].SourcePath == video,
    "Saved version did not retain source references.");
await service.SaveVersionAsync(project);
Check((await service.ListBackupsAsync(project.Id)).Count == 1, "Identical versions should not create duplicates.");
var backupDirectory = Path.GetDirectoryName(versions[0].ProjectPath)!;
var unrelated = Path.Combine(backupDirectory, "notes.klippbackup");
await File.WriteAllTextAsync(unrelated, "user file, not a generated backup");
for (var index = 0; index < 35; index++)
{
    project.Name = "Version " + index;
    await service.SaveVersionAsync(project);
}
Check((await service.ListBackupsAsync(project.Id)).Count == EditorProjectBackupService.MaximumVersions,
    "Backup retention did not keep exactly the configured version limit.");
Check(File.Exists(unrelated), "Retention deleted a file that was not generated by the backup service.");

var savePath = Path.Combine(projectDirectory, "example.klippproject");
await service.SaveAsync(project, savePath);
var references = await service.GetReferencedMediaPathsAsync();
Check(references.Contains(Path.GetFullPath(video)) && references.Contains(Path.GetFullPath(font)), "Version references were not included in retained project media.");
Check(references.Contains(Path.GetFullPath(processingOriginal)) && references.Contains(Path.GetFullPath(previousBake)),
    "Original and previous baked sources were not protected from media retention.");
var damaged = Path.Combine(projectDirectory, "damaged.klippproject");
await File.WriteAllTextAsync(damaged, "invalid json");
await service.SaveAsync(project, damaged);
Check(await service.TryLoadAsync(damaged) is not null, "An unreadable old project prevented a fresh save.");

var collector = new EditorProjectFilesService();
var collectedDirectory = Path.Combine(root, "Collected");
Directory.CreateDirectory(collectedDirectory);
project.Name = "Portable test";
var result = await collector.CollectAsync(project, collectedDirectory);
Check(result.FileCount == 8, "Collect did not deduplicate video/audio/font references or omitted processing sources.");
var portable = JsonSerializer.Deserialize<EditorProject>(await File.ReadAllTextAsync(result.ProjectPath))!;
Check(!Path.IsPathRooted(portable.Clips[0].SourcePath) && !Path.IsPathRooted(portable.Settings.TextFontFilePath),
    "Portable project still contains absolute media or font paths.");
Check(!Path.IsPathRooted(portable.Clips[0].VideoProcessing!.OriginalSourcePath) &&
      !Path.IsPathRooted(portable.Clips[0].VideoProcessing!.BakedSourcePath),
    "Portable project still contains absolute processing source paths.");
Check(portable.Id != project.Id && project.Clips[0].SourcePath == video,
    "Collect mutated the original project or kept its document identity.");
Check(portable.Clips[0].SourcePath != portable.Clips[1].SourcePath,
    "Files with the same name from different folders collided.");
var originalFolder = Path.GetDirectoryName(result.ProjectPath)!;
var movedFolder = Path.Combine(root, "Moved portable project");
Check(Path.GetFullPath(originalFolder).StartsWith(root + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase) &&
      Path.GetFullPath(movedFolder).StartsWith(root + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase),
    "Test move escaped its temporary workspace.");
Directory.Move(originalFolder, movedFolder);
var movedPath = Path.Combine(movedFolder, Path.GetFileName(result.ProjectPath));
var moved = (await service.TryLoadAsync(movedPath))!;
Check(File.Exists(moved.Clips[0].SourcePath) && File.Exists(moved.Clips[1].SourcePath) &&
      File.Exists(moved.AudioTracks[1].SourcePath) && File.Exists(moved.GraphicLayers[0].SourcePath) &&
      File.Exists(moved.Clips[0].LutPath) && File.Exists(moved.Settings.TextFontFilePath) &&
      File.Exists(moved.ExtraTextLayers[0].FontFilePath), "Moved portable project could not resolve all asset types.");
Check(File.Exists(moved.Clips[0].VideoProcessing!.OriginalSourcePath) && File.Exists(moved.Clips[0].VideoProcessing!.BakedSourcePath),
    "Moved portable project could not resolve original and previous baked media.");
Check(await File.ReadAllTextAsync(moved.Clips[0].SourcePath) == "first-video-payload" &&
      await File.ReadAllTextAsync(moved.Clips[1].SourcePath) == "second-video-payload",
    "Collected files did not preserve their contents.");
Check(await File.ReadAllTextAsync(video) == "first-video-payload" && await File.ReadAllTextAsync(font) == "font-payload",
    "Collect changed original files.");
var repeat = await collector.CollectAsync(project, collectedDirectory);
var another = await collector.CollectAsync(project, collectedDirectory);
Check(repeat.ProjectPath != another.ProjectPath && File.Exists(repeat.ProjectPath), "Collect overwrote an existing portable folder.");

var missingProject = EditorProjectService.Clone(project);
missingProject.Clips[0].SourcePath = Path.Combine(root, "not-found.mp4");
try { await collector.CollectAsync(missingProject, collectedDirectory); throw new Exception("Missing media was not rejected."); }
catch (FileNotFoundException) { checks++; }
var cancelDirectory = Path.Combine(root, "Cancelled");
Directory.CreateDirectory(cancelDirectory);
using var cancellation = new CancellationTokenSource();
var cancelProgress = new InlineProgress<EditorProjectCollectionProgress>(value => { if (value.CompletedFiles > 0) cancellation.Cancel(); });
try { await collector.CollectAsync(project, cancelDirectory, cancelProgress, cancellation.Token); throw new Exception("Cancellation was ignored."); }
catch (OperationCanceledException) { checks++; }
Check(!Directory.EnumerateFileSystemEntries(cancelDirectory).Any(), "Cancellation left a partial portable project.");

var nullableProjectPath = Path.Combine(root, "nullable.klippproject");
await File.WriteAllTextAsync(nullableProjectPath, "{\"Clips\":null,\"AudioTracks\":null,\"GraphicLayers\":null,\"ExtraTextLayers\":null,\"SubtitleLayers\":null,\"Settings\":null}");
Check(await service.TryLoadAsync(nullableProjectPath) is not null, "Legacy null collections were not normalized on load.");
checks += await LookPresetChecks.RunAsync(root);
checks += await EffectsWorkflowChecks.RunAsync(root);
checks += await SaveSerializationChecks.RunAsync(root);
checks += await MotionTrackingChecks.RunAsync(root);
checks += await ClipboardChecks.RunAsync(root);
checks += EffectRegionAnimationChecks.Run();
checks += await RecordingBookmarkChecks.RunAsync(root);
Console.WriteLine($"PASS: {checks} project-file and editor-workflow checks. Temporary artifacts: {root}");

sealed class InlineProgress<T>(Action<T> report) : IProgress<T>
{
    public void Report(T value) => report(value);
}
