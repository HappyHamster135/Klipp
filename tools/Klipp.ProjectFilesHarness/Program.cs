using System.Text.Json;
using Klipp.Desktop.Models;
using Klipp.Desktop.Services;

if (args.Contains("--recording-bookmarks-only"))
{
    var bookmarkRoot = Path.Combine(Path.GetTempPath(), "Klipp-RecordingBookmarks-" + Guid.NewGuid().ToString("N"));
